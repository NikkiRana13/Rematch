/**
 * Generates supabase/seed.sql from the verified TypeScript seed bank so answer keys stay
 * synchronized between local demo mode and Supabase. Run: npm run seed:sql
 */
import fs from "node:fs";
import path from "node:path";
import { SEED_PASSAGES, SEED_PRACTICE, SEED_QUESTIONS } from "../src/lib/content/seed";

const lit = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean" || typeof v === "number") return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (xs: string[]) => (xs.length ? `array[${xs.map(lit).join(", ")}]::text[]` : `'{}'::text[]`);
const json = (v: unknown) => `${lit(JSON.stringify(v))}::jsonb`;

const lines: string[] = ["-- GENERATED by scripts/generate-seed-sql.ts — do not edit by hand.", "begin;", ""];

for (const p of SEED_PASSAGES) {
  lines.push(
    `insert into public.passages (id, subject, grade_level, title, body, owner_id, source) values (${[p.id, p.subject, p.gradeLevel, p.title, p.body].map(lit).join(", ")}, null, 'seed') on conflict (id) do update set title = excluded.title, body = excluded.body;`,
  );
}
lines.push("");
for (const r of SEED_PRACTICE) {
  lines.push(
    `insert into public.practice_resources (id, subject, skill, kind, misconception, title, explanation, worked_example, verified) values (${[r.id, r.subject, r.skill, r.kind, r.misconception, r.title].map(lit).join(", ")}, ${arr(r.explanation)}, ${json(r.workedExample)}, ${r.verified}) on conflict (id) do update set title = excluded.title, explanation = excluded.explanation, worked_example = excluded.worked_example, verified = excluded.verified;`,
  );
}
lines.push("");
// Follow-up questions first so foreign keys resolve.
const ordered = [...SEED_QUESTIONS].sort((a, b) => Number(a.questionRole === "initial") - Number(b.questionRole === "initial"));
for (const q of ordered) {
  lines.push(
    `insert into public.questions (id, version, subject, grade_level, skill, skill_focus, question_role, passage_id, prompt, reasoning_prompt, answer_choices, correct_answer, reference_explanation, allowed_misconceptions, practice_resource_id, follow_up_question_id, verified, owner_id, source) values (${[
      q.id,
      q.version,
      q.subject,
      q.gradeLevel,
      q.skill,
      q.skillFocus,
      q.questionRole,
      q.passageId,
      q.prompt,
      q.reasoningPrompt,
    ]
      .map(lit)
      .join(", ")}, ${json(q.answerChoices)}, ${lit(q.correctAnswer)}, ${lit(q.referenceExplanation)}, ${arr(q.allowedMisconceptions)}, ${lit(q.practiceResourceId)}, ${lit(q.followUpQuestionId)}, ${q.verified}, null, 'seed') on conflict (id) do update set version = excluded.version, prompt = excluded.prompt, answer_choices = excluded.answer_choices, correct_answer = excluded.correct_answer, reference_explanation = excluded.reference_explanation, follow_up_question_id = excluded.follow_up_question_id, verified = excluded.verified;`,
  );
}
lines.push("", "commit;", "");

const out = path.join(process.cwd(), "supabase", "seed.sql");
fs.writeFileSync(out, lines.join("\n"));
console.log(`Wrote ${out}: ${SEED_PASSAGES.length} passages, ${SEED_PRACTICE.length} practice resources, ${SEED_QUESTIONS.length} questions.`);
